using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using PPDS.DocsGen.Common;
using PPDS.DocsGen.Libs;

namespace PPDS.DocsGen.Libs.Tests;

// Shared by the normal test project and a fixture-only offline console harness.
// All thirteen-input tests use synthetic bytes and an injected metadata generator.
internal static class LibraryCoverageFixtureChecks
{
    public static string[] Run(string fixtureAssembly, string workspace)
    {
        if (Directory.Exists(workspace)) throw new Exception("Test workspace must be fresh.");
        Directory.CreateDirectory(workspace);
        var passed = new List<string>();
        var generator = new LibraryReferenceGenerator();
        var actual = generator.GenerateWithCoverage(new GenerationInput(fixtureAssembly, workspace), default);
        Check(actual.Types.Any(type => type.FullName.EndsWith("HiddenHelper") && type.Hidden && type.PagePath is null), "hidden types remain in the inventory");
        var undocumented = actual.Generation.Files.Single(file => file.RelativePath.EndsWith("/UndocumentedThing.md"));
        Check(undocumented.Contents.Contains("Documentation summary unavailable") && undocumented.Contents.Contains("Value"), "undocumented type and member survive with honest fallback");
        Check(actual.Types.Where(type => !type.Hidden).All(type => actual.Generation.Files.Any(file => file.RelativePath == type.PagePath)), "every visible fixture type has a page");
        var repeated = generator.GenerateWithCoverage(new GenerationInput(fixtureAssembly, workspace), default);
        Check(actual.Generation.Files.SequenceEqual(repeated.Generation.Files), "real fixture reflection is deterministic");
        Check(actual.Generation.Files.Single(file => file.RelativePath.EndsWith("/ExternalDocsConsumer.md")).Contents.Contains("External.Unresolvable.Api.SomeThing"), "inheritdoc fallback remains intact");

        var inputs = new List<LibraryCoverageInput>();
        var results = new Dictionary<string, LibraryGenerationResult>(StringComparer.OrdinalIgnoreCase);
        foreach (var package in LibraryCoverageRunner.Packages)
        {
            foreach (var tfm in LibraryCoverageRunner.Frameworks(package))
            {
                var directory = Path.Combine(workspace, "inputs", package, tfm);
                Directory.CreateDirectory(directory);
                var dll = Path.Combine(directory, package + ".dll");
                var xml = Path.ChangeExtension(dll, ".xml");
                File.WriteAllText(dll, "synthetic metadata input " + package + "/" + tfm);
                File.WriteAllText(xml, "synthetic XML input " + package + "/" + tfm);
                inputs.Add(new(package, tfm, Path.GetRelativePath(workspace, dll), Hash(dll), Hash(xml)));
                var shortName = package[5..];
                var banner = BannerHelper.AutogeneratedBanner("libs-reflect") + "\n\n";
                var content = banner + (package == "PPDS.Auth" ? "# Fixture\n\n" + tfm + "\n" : "# Fixture\n\nCommon.\n");
                var pagePath = shortName + (package == "PPDS.Auth" ? "/Nested/Fixture`2.md" : "/Fixture.md");
                results.Add(dll, new LibraryGenerationResult(new GenerationResult(
                    [new(pagePath, content), new(shortName + "/_index.md", banner + "# Index\n\n[Fixture](./" + pagePath[(shortName.Length+1)..] + ")\n")], []),
                    package, tfm == "net462" ? ".NETFramework,Version=v4.6.2" : ".NETCoreApp,Version=v" + tfm[3..],
                    [new(package + ".Fixture", false, pagePath), new(package + ".Hidden", true, null)]));
            }
        }
        var manifest = Path.Combine(workspace, "manifest.json");
        var calls = 0;
        LibraryGenerationResult Fake(string path, CancellationToken token) { calls++; return results[path]; }
        void Write(IEnumerable<LibraryCoverageInput> entries) => File.WriteAllText(manifest,
            JsonSerializer.Serialize(new LibraryCoverageManifest(1, entries.ToArray()), LibraryCoverageRunner.JsonOptions));
        Write(inputs);
        var output = Path.Combine(workspace, "complete");
        LibraryCoverageRunner.Run(manifest, output, Fake);
        Check(calls == 13 && File.Exists(Path.Combine(output, "Query", "Fixture.md")), "all thirteen inputs including Query reflected");
        var variantPage = Path.Combine(output, "Auth", "Nested", "Fixture`2.md");
        Check(File.ReadAllText(variantPage).Contains("Framework-specific reference")
            && File.Exists(Path.Combine(output, "by-framework", "net8.0", "Auth", "Nested", "Fixture`2.md"))
            && File.Exists(Path.Combine(output, "by-framework", "net10.0", "Auth", "Nested", "Fixture`2.md")), "framework differences retain variants without overwrite");
        var links = System.Text.RegularExpressions.Regex.Matches(File.ReadAllText(variantPage), @"\]\(([^)]+)\)");
        Check(links.Count == 3 && links.All(match =>
            File.Exists(Path.GetFullPath(Uri.UnescapeDataString(match.Groups[1].Value), Path.GetDirectoryName(variantPage)!)))
            && links.All(match => match.Groups[1].Value.Contains("%60")), "nested escaped framework links resolve to every retained page");
        Check(Directory.EnumerateFiles(output, "*.md", SearchOption.AllDirectories).All(path =>
            File.ReadLines(path).First() == BannerHelper.AutogeneratedBanner("libs-reflect")),
            "common, variant, index and per-framework pages preserve the required first-line banner");
        using (var receipt = JsonDocument.Parse(File.ReadAllText(Path.Combine(output, "coverage-evidence.json"))))
        {
            Check(receipt.RootElement.GetProperty("inputs").GetArrayLength() == 13
                && receipt.RootElement.GetProperty("kind").GetString() == "source-reflection-library-coverage", "receipt records exact coverage without stable-publication claim");
            foreach(var file in receipt.RootElement.GetProperty("files").EnumerateArray())
                if (Hash(Path.Combine(output, file.GetProperty("path").GetString()!)) != file.GetProperty("sha256").GetString())
                    throw new Exception("Output receipt hash mismatch.");
            passed.Add("every emitted file hash matches receipt");
        }
        Refused("existing-output", () => LibraryCoverageRunner.Run(manifest, output, Fake), outputMayExist:true);
        Write(inputs.Take(12));
        Refused("missing-input", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "missing-input"), Fake), expectNoCalls:true);
        Write(inputs.Take(12).Append(inputs[0]));
        Refused("duplicate-input", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "duplicate-input"), Fake), expectNoCalls:true);
        Write(inputs.Select((input, index) => index == 12 ? input with { AssemblySha256 = new string('0', 64) } : input));
        Refused("last-input-hash-mismatch", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "last-input-hash-mismatch"), Fake), expectNoCalls:true);
        Write(inputs.Select((input, index) => index == 0 ? input with { XmlSha256 = new string('0', 64) } : input));
        Refused("xml-hash-mismatch", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "xml-hash-mismatch"), Fake), expectNoCalls:true);
        Write(inputs.Select((input, index) => index == 0 ? input with { Assembly = "../outside.dll" } : input));
        Refused("escaping-input", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "escaping-input"), Fake), expectNoCalls:true);
        Write(inputs);
        var first = results.Keys.First();
        var original = results[first];
        results[first] = original with { TargetFramework = ".NETCoreApp,Version=v99.0" };
        Refused("wrong-framework", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "wrong-framework"), Fake));
        results[first] = original with { AssemblyName = "Foreign.Library" };
        Refused("wrong-assembly", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "wrong-assembly"), Fake));
        results[first] = original with { Types = [new("Missing.Type", false, "Auth/Missing.md")] };
        Refused("missing-visible-page", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "missing-visible-page"), Fake));
        results[first] = original with { Generation = original.Generation with
            { Files = original.Generation.Files.Select((file, index) => index == 0 ? file with { Contents = "# Missing banner\n" } : file).ToArray() } };
        Refused("missing-generated-banner", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "missing-generated-banner"), Fake));
        results[first] = original;
        using var cancellation = new CancellationTokenSource();
        cancellation.Cancel();
        Refused("cancelled-before-reflection", () => LibraryCoverageRunner.Run(manifest, Path.Combine(workspace, "cancelled-before-reflection"), Fake, cancellation.Token), expectNoCalls:true);
        var fakeLeaf = Path.Combine(workspace, "simulated", "leaf.json");
        Refused("linked-manifest-file", () => LibraryCoverageRunner.RejectLinks(fakeLeaf, attributes: path =>
            path == fakeLeaf ? FileAttributes.ReparsePoint : FileAttributes.Directory));
        Refused("linked-manifest-root", () => LibraryCoverageRunner.RejectLinks(fakeLeaf, attributes: path =>
            path == Path.GetDirectoryName(fakeLeaf) ? FileAttributes.ReparsePoint : FileAttributes.Directory));
        Refused("linked-output-ancestor", () => LibraryCoverageRunner.RejectLinks(fakeLeaf, allowMissing:true, attributes: path =>
            path == fakeLeaf ? throw new FileNotFoundException() : path == workspace ? FileAttributes.ReparsePoint : FileAttributes.Directory));
        LibraryCoverageRunner.RejectLinks(fakeLeaf, allowMissing:true, attributes: path =>
            path == fakeLeaf ? throw new DirectoryNotFoundException() : FileAttributes.Directory);
        passed.Add("fresh output path allowed only with unlinked ancestors (simulated attributes)");
        return passed.ToArray();

        void Check(bool condition, string name) { if (!condition) throw new Exception(name); passed.Add(name); }
        void Refused(string name, Action action, bool expectNoCalls = false, bool outputMayExist = false)
        {
            var before = calls;
            try { action(); } catch (Exception error) when (error is InvalidDataException or InvalidOperationException or OperationCanceledException)
            {
                if (expectNoCalls && calls != before) throw new Exception(name + " reflected before validating all inputs");
                if (!outputMayExist && Directory.Exists(Path.Combine(workspace, name))) throw new Exception(name + " wrote output before refusal");
                passed.Add(name + " refused without output"); return;
            }
            throw new Exception(name + " was not refused");
        }
    }
    private static string Hash(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant();
}
